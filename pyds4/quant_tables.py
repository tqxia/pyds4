"""Static lookup tables for IQ2_* dequantization.

Ported verbatim from ``ds4_iq2_tables_cuda.inc`` (which itself is the upstream
``llama.cpp`` / ``ggml`` table — the values are part of the IQ2_XXS spec and
must not be changed). The same tables appear in ``ds4.c`` at lines 232..308.

Two raw tables:

- ``KSIGNS_IQ2XS`` (128 entries): a bitmask per "sign index". For a 7-bit sign
  index ``s``, the byte ``KSIGNS_IQ2XS[s]`` encodes the parity of 8 grid
  positions: bit ``b`` set means position ``b`` should be negated. Bit 7 is a
  whole-mask parity (so even-popcount masks land in 0..127 and odd-popcount
  masks have bit 7 flipped — but we only use the low 7 bits indexed by ``s``
  for sign lookup).

- ``IQ2XXS_GRID`` (256 entries): each ``uint64`` packs 8 little-endian
  ``uint8`` values from the IQ2_XXS coordinate book. Each byte is a small
  positive integer (e.g. 0x08, 0x19, 0x2b) that represents the unsigned
  magnitude of one quantized element; the sign comes from the ksigns lookup.

We also precompute two derived tables for vectorized dequant:

- ``IQ2XXS_GRID_BYTES`` (256, 8) int8 — the grid uint64s split into 8 bytes
  little-endian. Indexing with a grid byte (0..255) yields the 8 magnitudes.
- ``KSIGNS_IQ2XS_MASK`` (128, 8) int8 — the sign bytes expanded to +1 / -1
  per position. Indexing with a 7-bit sign index yields the sign vector.

Cross-checked against ``ds4.c::iq2xxs_signed_grid_init`` (line 314): a
combination of these two tables is equivalent to ds4's runtime-built
``iq2xxs_signed_grid[256][128][8]`` (which we'd need 256 KiB to store
materialized, vs. 2 KiB + 1 KiB here).
"""

