def _build_grid_bytes() -> np.ndarray:
    """Expand IQ2XXS_GRID into a (256, 8) int8 array, little-endian per uint64.

    All packed values are < 0x80, so int8 and uint8 alias the same bit pattern.
    """
    bytes_le = IQ2XXS_GRID.view(np.uint8).reshape(256, 8)
    return bytes_le.astype(np.int8)


def _build_ksigns_mask() -> np.ndarray:
    """Expand KSIGNS_IQ2XS into a (128, 8) int8 array of +1/-1 per position.

    Mirrors ds4.c::iq2xxs_signed_grid_init (line 318):
        iq2xxs_signs[s][j] = (signs & kmask_iq2xs[j]) ? -1 : 1
    """
    signs = KSIGNS_IQ2XS[:, None]               # (128, 1)
    masks = KMASK_IQ2XS[None, :]                # (1, 8)
    is_neg = (signs & masks) != 0               # (128, 8) bool
    return np.where(is_neg, np.int8(-1), np.int8(1))


IQ2XXS_GRID_BYTES = _build_grid_bytes()         # (256, 8) int8
KSIGNS_IQ2XS_MASK = _build_ksigns_mask()        # (128, 8) int8
